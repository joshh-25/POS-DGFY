import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const sourcePath = path.join(repoRoot, 'src/modules/geoSearch/data/phLocalAddressSource.json');
const outputPath = path.join(repoRoot, 'src/modules/geoSearch/data/phLocalAddressDataset.js');

const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));

const precisionRank = {
    barangay: 0,
    city: 1,
    province: 2,
    coordinate_only: 3
};

const entries = [...source.entries]
    .map((entry) => ({
        ...entry,
        latitude: Number(entry.latitude),
        longitude: Number(entry.longitude),
        maxDistanceKm: Number(entry.maxDistanceKm)
    }))
    .sort((left, right) => {
        const precisionDelta = (precisionRank[left.precision] ?? 99) - (precisionRank[right.precision] ?? 99);
        if (precisionDelta !== 0) return precisionDelta;
        return String(left.label).localeCompare(String(right.label));
    });

const output = `// Generated by backend/scripts/build-ph-local-address-dataset.js from phLocalAddressSource.json.
// Do not edit this file directly; update the source JSON and regenerate.
export const PH_LOCAL_ADDRESS_PROVIDER = ${JSON.stringify(source.provider)};

export const PH_LOCAL_ADDRESS_PROVENANCE = Object.freeze(${JSON.stringify({
    provider: source.provider,
    generatedAt: source.generatedAt,
    psgcRelease: source.psgcRelease,
    psgcApiBaseUrl: source.psgcApiBaseUrl,
    sourceNotes: source.sourceNotes,
    sources: source.sources
}, null, 4)});

export const PH_LOCAL_ADDRESS_DATASET = Object.freeze(${JSON.stringify(entries, null, 4)});
`;

fs.writeFileSync(outputPath, output, 'utf8');
console.log(`Wrote ${entries.length} PH-local address entries to ${path.relative(repoRoot, outputPath)}`);
